"""Is this corpus allowed to be Stage 1 evidence? One question, answered explicitly.

WHY THIS EXISTS
===============
The failure mode this prevents has a name: *"we ran Stage 1 on whatever CSV was
in the folder."*

It is not hypothetical here. `data/ohlcv/` contains
`BYBIT_SPOT_ETH_USDT_1H.csv.gz` and `BYBIT_SPOT_SOL_USDT_1H.csv.gz` — 5,000 bars
each, correct CoinAPI-shaped headers, plausible prices. A future session looking
for "multi-asset data" would find them immediately. They are **synthetic**,
generated by `tools/make_dataset.py` from a stochastic model, and any Sharpe or
win rate measured on them is a property of the generator.

So this module answers, per corpus, in a field rather than by implication:

    eligible_for_stage1 : bool
    ineligible_reasons  : list[str]   -- never empty when False

ELIGIBILITY IS NOT EDGE
=======================
A corpus marked eligible is a set of bars a measurement may legitimately be run
*against*. It says nothing about whether any signal times them. Nothing here
reopens `RESEARCH_CLOSE_STAGE1.md`, clears a signal, changes M1/M2, or touches
`ProjectStatus.cleared_edge_signal`. The BTC daily corpus is eligible, has 2,564
bars, and produced an ABSENT reading — eligibility and edge are different
questions and this module only answers the first.

HOW IT DECIDES
==============
It keys on the convention the repository already has rather than inventing a
second one. Every corpus directory carries a `MANIFEST.json` with a `synthetic`
boolean and a `bar_seconds` integer; the real corpora additionally carry a
`source.exchange`. That is the ground truth, not the directory name — a folder
called `real_something` proves nothing.

`is_synthetic` is checked **first and independently**. There is no combination of
other fields that can make a synthetic corpus eligible, and
`tests/test_data_contract.py` asserts that by forcing every other field to a
passing value.

FAIL CLOSED
===========
An unreadable manifest, an unparseable file, a missing directory, an unknown
interval: all produce `eligible_for_stage1: False` with a recorded reason. The
answer to "may I use this?" defaults to no, and the answer is never a shrug.
"""
