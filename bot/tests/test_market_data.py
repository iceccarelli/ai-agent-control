def laddered_book(levels=5, base=100.0, step=1.0, size=1.0):
    """A book with equal size on every level, symmetric around ``base``."""
    bids = [(base - step * (i + 1), size) for i in range(levels)]
    asks = [(base + step * (i + 1), size) for i in range(levels)]
    return BookState("SYM").apply_all(snapshot(1, bids, asks))


class TestSlippage:
    def test_a_touch_sized_order_costs_the_half_spread(self):
        features = laddered_book().features()
        notional = features.ask_levels[0].notional
        assert features.slippage_bps_for(notional, "BUY") == pytest.approx(
            (101.0 - 100.0) / 100.0 * 10_000
        )

    def test_slippage_grows_with_size(self):
        features = laddered_book(levels=5, size=1.0).features()
        costs = [features.slippage_bps_for(n, "BUY") for n in (101, 250, 400, 500)]
        assert all(cost is not None for cost in costs)
        assert costs == sorted(costs), f"slippage must not fall with size: {costs}"
        assert costs[-1] > costs[0]

    def test_slippage_is_never_negative_on_an_uncrossed_book(self):
        """A negative cost would mean the book paid you to trade."""
        features = laddered_book().features()
        for side in ("BUY", "SELL"):
            for notional in (50, 150, 300):
                assert features.slippage_bps_for(notional, side) >= 0.0

    def test_buy_and_sell_are_comparable_on_a_symmetric_book(self):
        """Roughly equal, not exactly.

        The levels are symmetric in *size* but sit at different absolute prices
        (99, 98, 97 against 101, 102, 103), so a fixed notional buys fewer units
        going up than going down and the two VWAPs land a couple of percent
        apart. That residual is arithmetic, not a bug — demanding exact equality
        would only be satisfiable by a book that cannot exist.
        """
        features = laddered_book().features()
        assert features.slippage_bps_for(250, "BUY") == pytest.approx(
            features.slippage_bps_for(250, "SELL"), rel=0.05
        )

    def test_buying_walks_the_asks_and_selling_walks_the_bids(self):
        """Direction correctness: a thin ask makes buying expensive, not selling."""
        state = BookState("SYM").apply_all(snapshot(
            1, [(99.0, 100.0), (98.0, 100.0)], [(101.0, 0.05), (110.0, 100.0)]))
        features = state.features()
        assert features.slippage_bps_for(2_000, "BUY") > \
            features.slippage_bps_for(2_000, "SELL")

    def test_an_order_larger_than_the_book_returns_none(self):
        """Not the last level's price extrapolated.

        Running out of book is the case where real slippage is worst, so
        extrapolating understates the cost precisely when it matters most — and
        turns "your order is too big for this market" into a modest-looking
        number a sizing routine will act on.
        """
        features = laddered_book(levels=3, size=1.0).features()
        assert features.slippage_bps_for(10_000_000, "BUY") is None

    def test_fillable_notional_explains_a_none(self):
        features = laddered_book(levels=3, size=1.0).features()
        capacity = features.fillable_notional("BUY")
        assert features.slippage_bps_for(capacity * 0.9, "BUY") is not None
        assert features.slippage_bps_for(capacity * 1.1, "BUY") is None

    def test_a_crossed_book_returns_none_rather_than_a_cost(self):
        state = BookState("SYM").apply_all(snapshot(1, [(102.0, 5.0)], [(101.0, 5.0)]))
        assert state.features().slippage_bps_for(10.0, "BUY") is None

    def test_a_one_sided_book_returns_none(self):
        state = BookState("SYM").apply_all(snapshot(1, [(100.0, 5.0)], []))
        assert state.features().slippage_bps_for(10.0, "SELL") is None

    def test_a_non_positive_notional_raises(self):
        features = laddered_book().features()
        for bad in (0.0, -100.0, float("nan"), float("inf")):
            with pytest.raises(ValueError):
                features.slippage_bps_for(bad, "BUY")

    def test_an_unknown_side_raises(self):
        with pytest.raises(ValueError):
            laddered_book().features().slippage_bps_for(100.0, "sideways")

    def test_only_the_measured_levels_are_used(self):
        """`features(levels=1)` must not answer for size that level cannot hold."""
        state = laddered_book(levels=5, size=1.0)
        assert state.features(levels=1).slippage_bps_for(400, "BUY") is None
        assert state.features(levels=5).slippage_bps_for(400, "BUY") is not None

    def test_selling_into_the_crash_costs_far_more_than_in_calm(
            self, btc_bars, btc_events):
        """The reason to ship a book at all.

        The bid thins and the spread widens together, so a stop-loss — a market
        sell — is most expensive exactly when it fires. No constant-slippage
        backtest can see this.
        """
        calm, crash = [], []
        for step in md.replay(btc_bars.bars, btc_events.events, levels=10):
            cost = step.features.slippage_bps_for(50_000.0, "SELL")
            if cost is None:
                continue
            if step.index < 1_500:
                calm.append(cost)
            elif 2_700 <= step.index < 3_000:
                crash.append(cost)
        assert len(calm) > 500 and len(crash) > 100
        calm_mean = sum(calm) / len(calm)
        crash_mean = sum(crash) / len(crash)
        assert crash_mean > 5 * calm_mean, (
            f"crash slippage {crash_mean:.2f} bps vs calm {calm_mean:.2f} bps"
        )


