    def test_the_manifest_declares_the_data_synthetic(self, manifest):
        """Provenance must survive a copy of the directory."""
        assert manifest["synthetic"] is True
        assert "SYNTHETIC" in manifest["warning"]
        assert md.verify_manifest(DATA).synthetic is True

    def test_an_edited_file_is_detected(self, tmp_path):
        """The failure this exists for: someone "just fixing" a row by hand."""
        import shutil

        root = tmp_path / "data"
        shutil.copytree(DATA, str(root))
        target = root / "anomalies" / "quotes_crossed_book.csv"
        target.write_text(
            target.read_text(encoding="utf-8").replace("62010", "62011"),
            encoding="utf-8",
        )
        report = md.verify_manifest(str(root))
        assert not report.ok
        assert any("CONTENT CHANGED" in problem for problem in report.problems)
        with pytest.raises(md.ManifestError):
            report.raise_if_bad()

    def test_a_missing_file_is_detected(self, tmp_path):
        import shutil

        root = tmp_path / "data"
        shutil.copytree(DATA, str(root))
        os.remove(str(root / "ohlcv" / "BYBIT_SPOT_SOL_USDT_1H.csv.gz"))
        report = md.verify_manifest(str(root))
        assert not report.ok
        assert any("missing" in problem for problem in report.problems)

    def test_recompression_is_not_reported_as_corruption(self, tmp_path):
        """Re-gzipping changes every byte and no rows.

        Calling that corruption trains people to ignore this check, which is the
        only way a check like this actually fails.
        """
        import shutil

        root = tmp_path / "data"
        shutil.copytree(DATA, str(root))
        target = root / "ohlcv" / "BYBIT_SPOT_SOL_USDT_1H.csv.gz"
        raw = gzip.decompress(target.read_bytes())
        buffer = io.BytesIO()
        with gzip.GzipFile(fileobj=buffer, mode="wb", compresslevel=1,
                           filename="", mtime=12345) as handle:
            handle.write(raw)
        target.write_bytes(buffer.getvalue())

        report = md.verify_manifest(str(root))
        assert report.ok, report.problems
        assert "ohlcv/BYBIT_SPOT_SOL_USDT_1H.csv.gz" in report.recompressed

    def test_a_missing_manifest_is_a_problem_not_a_pass(self, tmp_path):
        report = md.verify_manifest(str(tmp_path))
        assert not report.ok

    def test_a_corrupt_manifest_is_a_problem_not_a_pass(self, tmp_path):
        (tmp_path / "MANIFEST.json").write_text("{not json", encoding="utf-8")
        report = md.verify_manifest(str(tmp_path))
        assert not report.ok

    def test_every_corpus_file_is_listed(self, manifest):
        """Every file in THIS corpus root must be in THIS corpus's manifest.

        `data/real/` is a corpus in its own right, with its own MANIFEST.json
        and its own README — real Bitstamp data, not the synthetic corpus. It
        is verified by its own manifest, not by this one, and folding the two
        together would let a real file be checked against a synthetic hash.
        Nested roots are therefore skipped here and checked below.
        """
        on_disk = set()
        for folder, dirs, names in os.walk(DATA):
            dirs[:] = [
                d for d in dirs
                if not os.path.exists(os.path.join(folder, d, "MANIFEST.json"))
            ]
            for name in names:
                if name in ("MANIFEST.json", "README.md"):
                    continue
                on_disk.add(
                    os.path.relpath(os.path.join(folder, name), DATA).replace(os.sep, "/")
                )
        assert on_disk == set(manifest["files"]), (
            "a corpus file outside the manifest is a file nothing verifies"
        )

    def test_a_nested_corpus_root_verifies_against_its_own_manifest(self):
        """If data/real/ is present, it must verify — and declare itself REAL."""
        nested = os.path.join(DATA, "real")
        if not os.path.exists(os.path.join(nested, "MANIFEST.json")):
            pytest.skip("no data/real corpus in this checkout")
        report = md.verify_manifest(nested)
        assert report.problems == [], report.problems
        assert report.synthetic is False, (
            "data/real declares itself synthetic; that is the one field every "
            "report prints and it must be true"
        )


