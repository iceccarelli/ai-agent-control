class TestReplayCannotSeeTheFuture:
    def test_no_event_after_the_bar_close_is_ever_applied(self, btc_bars, btc_events):
        for step in md.replay(btc_bars.bars[:800], btc_events.events):
            assert step.last_event_us is None or step.last_event_us <= step.cutoff_us

    def test_the_book_matches_an_independently_truncated_stream(
            self, btc_bars, btc_events):
        """The strongest form of the claim.

        Rebuild the book from scratch out of only those events at or before the
        bar's close, computed without the iterator's help, and require the same
        touch. If `replay` leaked a single future event the two would differ.
        """
        events = btc_events.events
        for step in md.replay(btc_bars.bars[:40], events):
            truncated = BookState(events[0].symbol_id, strict=False)
            for event in events:
                if event.time_coinapi_us > step.cutoff_us:
                    break
                truncated.apply(event)
            assert truncated.best_bid == step.book.best_bid
            assert truncated.best_ask == step.book.best_ask

    def test_the_cut_is_on_receive_time_not_exchange_time(self, btc_bars, btc_events):
        """Cutting on time_exchange grants the collection latency as foresight.

        It is a few hundred microseconds here, which is exactly why it has to be
        right here: the same code against a feed with 400ms of latency would be
        reading the future by a whole trading decision.
        """
        bars = btc_bars.bars[:200]
        by_receive = [s.events_applied for s in md.replay(bars, btc_events.events)]
        by_exchange = [s.events_applied for s in
                       md.replay(bars, btc_events.events, use_coinapi_time=False)]
        assert by_exchange >= by_receive
        assert by_exchange != by_receive, (
            "the two cuts must differ, or the corpus has no latency to model"
        )

    def test_events_applied_only_ever_increases(self, btc_bars, btc_events):
        counts = [s.events_applied for s in md.replay(btc_bars.bars[:500],
                                                      btc_events.events)]
        assert counts == sorted(counts)

    def test_each_step_yields_a_detached_book(self, btc_bars, btc_events):
        """A consumer mutating the yielded book must not change the next step."""
        steps = []
        symbol = btc_events.events[0].symbol_id
        for step in md.replay(btc_bars.bars[:5], btc_events.events):
            steps.append(step)
            # Wipe the yielded book entirely. If the iterator were handing out
            # its own state, the next step would start from this rubble.
            step.book.apply(ev(step.cutoff_us + 1, True, 1.0, 999.0, "SNAPSHOT",
                               symbol=symbol))
        assert all(len(s.book.bids) == 1 for s in steps), "each was clobbered"
        for step in md.replay(btc_bars.bars[:5], btc_events.events):
            assert len(step.book.bids) > 1, "a later step inherited the damage"

    def test_one_step_per_bar_in_order(self, btc_bars, btc_events):
        bars = btc_bars.bars[:120]
        steps = list(md.replay(bars, btc_events.events))
        assert [s.index for s in steps] == list(range(len(bars)))
        assert [s.bar for s in steps] == bars

    def test_unsorted_events_are_refused_not_sorted(self, btc_bars, btc_events):
        """Sorting inside the replay would mask an unsorted — and probably
        incomplete — source."""
        events = list(btc_events.events[:500])
        events[100], events[300] = events[300], events[100]
        with pytest.raises(MarketDataError):
            list(md.replay(btc_bars.bars[:5], events))

    def test_unsorted_bars_are_refused(self, btc_bars, btc_events):
        bars = list(btc_bars.bars[:10])
        bars[3], bars[7] = bars[7], bars[3]
        with pytest.raises(MarketDataError):
            list(md.replay(bars, btc_events.events))

    def test_replay_works_with_bars_that_carry_only_millisecond_stamps(self):
        """`Bar` built the `backtest.Bar` way leaves start_us at 0.

        Without the fallback every such bar claims to start at the epoch and the
        whole series reads as non-monotonic.
        """
        bars = [md.Bar(1_709_251_200_000 + i * 3_600_000, 100.0, 101.0, 99.0,
                       100.5, 1.0) for i in range(3)]
        steps = list(md.replay(bars, []))
        assert len(steps) == 3
        assert steps[1].cutoff_us > steps[0].cutoff_us

    def test_replay_over_an_empty_event_stream_yields_empty_books(self, btc_bars):
        steps = list(md.replay(btc_bars.bars[:3], []))
        assert all(s.book.is_empty and s.features.mid is None for s in steps)

    def test_the_book_is_never_crossed_anywhere_in_the_shipped_stream(
            self, btc_bars, btc_events):
        """A crossed book must mean "something is wrong", not "the fixture is
        lazy". If the generator's sampling could leave stale levels crossing the
        new touch, every crossed-book test above would be testing the fixture.
        """
        crossed = 0
        for step in md.replay(btc_bars.bars, btc_events.events):
            if step.book.is_crossed:
                crossed += 1
        assert crossed == 0

    def test_the_shipped_stream_replays_without_a_single_integrity_warning(
            self, btc_bars, btc_events):
        """The generator's update semantics and the loader's must agree exactly."""
        last = None
        for step in md.replay(btc_bars.bars, btc_events.events, strict_book=True):
            last = step
        assert last is not None and last.book.integrity_warnings == []


