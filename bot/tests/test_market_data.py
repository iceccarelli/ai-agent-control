"""Market-data loader and microstructure tests.

The shape of this file follows `tests/test_indicators.py`: assert the property
that would actually be violated by the bug, against real artefacts rather than
mocks. Where that file checks RSI against Wilder's published worked example,
this one checks every rejection path against a file in `data/anomalies/` that is
broken on purpose — a mock that raises the exception you wrote it to raise
proves nothing about a vendor file.

The three claims worth stating plainly, because they are what the whole module
is for:

1. **Nothing is fabricated.** A one-sided or crossed book yields ``None``, not a
   mid. A notional larger than the visible book yields ``None``, not the last
   level's price extrapolated.
2. **Nothing is dropped silently.** Every refused row comes back with a line
   number and a reason, and the good rows around it survive.
3. **The future is unreachable, not merely unused.** ``replay`` is checked
   against an independently computed truncation of the event stream, so the
   test would fail if the iterator leaked so much as one event.

Everything here is offline. The corpus is generated by `tools/make_dataset.py`
and is shipped in the repository; no test reaches the network.
"""
