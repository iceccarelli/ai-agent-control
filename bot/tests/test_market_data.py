class TestTimestamps:
    def test_parses_the_seven_digit_coinapi_form(self):
        assert md.parse_timestamp("2024-03-01T00:00:00.0000000Z") == 1_709_251_200_000_000

    def test_round_trips_through_format(self):
        for text in ("2024-03-01T00:00:00.0000000Z",
                     "2024-02-29T23:59:59.9999990Z",
                     "2025-12-31T12:34:56.1234560Z"):
            assert md.format_timestamp(md.parse_timestamp(text)) == text

    def test_the_fast_path_agrees_with_the_regex_path(self):
        """The 28-char fast path must not accept or compute anything different.

        A fast path that disagrees with the strict parser is a way to smuggle a
        malformed timestamp past validation, so this compares them directly by
        forcing the slow path with a leading space.
        """
        for text in ("2024-03-01T00:00:00.5327850Z",
                     "2024-07-04T18:22:09.0000010Z",
                     "2024-12-31T23:59:59.9999999Z"):
            assert md.parse_timestamp(text) == md.parse_timestamp(" " + text)

    def test_leap_day_is_handled(self):
        assert md.parse_timestamp("2024-02-29T00:00:00.0000000Z") > 0
        with pytest.raises(MarketDataError):
            md.parse_timestamp("2023-02-29T00:00:00.0000000Z")

    def test_a_missing_z_is_rejected_not_assumed_utc(self):
        """Assuming UTC on an unmarked timestamp shifts a whole series silently."""
        with pytest.raises(MarketDataError):
            md.parse_timestamp("2024-03-01T00:00:00.0000000")

    def test_an_offset_timezone_is_rejected(self):
        with pytest.raises(MarketDataError):
            md.parse_timestamp("2024-03-01T00:00:00.0000000+02:00")

    @pytest.mark.parametrize("spelling", ["Z", "+00:00", "+0000"])
    def test_every_spelling_of_utc_gives_the_same_instant(self, spelling):
        """`+00:00` is UTC. Slice 38: refusing it silently dropped 571 bars.

        The corpus extension the human shipped writes `+00:00` where the older
        rows write `Z`. `load_ohlcv` rejected all 571 new bars as BAD_TIMESTAMP
        while the intake report went on calling the corpus 3,135 bars and
        eligible — the measurement would have run on the old truncated window
        and been written up as the full history.
        """
        assert (md.parse_timestamp("2024-03-01T00:00:00.0000000" + spelling)
                == md.parse_timestamp("2024-03-01T00:00:00.0000000Z"))

    @pytest.mark.parametrize("offset", ["+02:00", "-05:00", "+0530", "-00:00"])
    def test_a_non_utc_offset_is_still_rejected(self, offset):
        """The widening is one more spelling of UTC, not a conversion.

        `-00:00` is in this list deliberately: RFC 3339 gives it the meaning
        "the local offset is unknown", which is not a claim of UTC, and this
        parser does not guess.
        """
        with pytest.raises(MarketDataError):
            md.parse_timestamp("2024-03-01T00:00:00.0000000" + offset)

    def test_the_fast_path_and_the_regex_agree(self):
        """The 28-character fast path must not accept more than the regex.

        It is only reachable for the `Z` form, so the `+00:00` form has to go
        through the general path — and both have to produce the same integer.
        """
        canonical = "2024-03-01T00:00:00.0000000Z"
        assert len(canonical) == 28
        assert (md.parse_timestamp(canonical)
                == md.parse_timestamp("2024-03-01T00:00:00+00:00")
                == 1_709_251_200_000_000)


class TestTradesCountIsTheOnlyOptionalColumn:
    """Slice 38. A blank `trades_count` is "not reported"; a blank price is a bug.

    The Bitstamp extension leaves `trades_count` empty where the older rows
    write `0`. That column is 0 for all 2,564 original bars — the 1-minute
    archive does not report it — so a blank carries the same information,
    spelled honestly. Nothing reads it. Every other column stays fatal.
    """

    def _row(self, **overrides):
        cells = {"time_period_start": "2024-03-01T00:00:00.0000000Z",
                 "time_period_end": "2024-03-02T00:00:00.0000000Z",
                 "time_open": "2024-03-01T00:00:00.0000000Z",
                 "time_close": "2024-03-01T23:59:00.0000000Z",
                 "price_open": "100", "price_high": "110",
                 "price_low": "90", "price_close": "105",
                 "volume_traded": "12.5", "trades_count": "0"}
        cells.update(overrides)
        return ",".join(cells[c] for c in (
            "time_period_start", "time_period_end", "time_open", "time_close",
            "price_open", "price_high", "price_low", "price_close",
            "volume_traded", "trades_count"))

    def _load(self, tmp_path, row):
        header = ("time_period_start,time_period_end,time_open,time_close,"
                  "price_open,price_high,price_low,price_close,volume_traded,"
                  "trades_count")
        path = tmp_path / "one.csv"
        path.write_text(header + "\n" + row + "\n")
        return md.load_ohlcv(str(path))

    def test_a_blank_trades_count_loads_as_zero(self, tmp_path):
        load = self._load(tmp_path, self._row(trades_count=""))
        assert len(load.bars) == 1
        assert load.rejections == []
        assert load.bars[0].trades == 0

    def test_a_blank_close_is_still_fatal(self, tmp_path):
        """The decisive contrast. An empty close becoming 0.0 is the bug this
        loader exists to catch, and a blank cell is indistinguishable from a
        truncated write."""
        load = self._load(tmp_path, self._row(price_close=""))
        assert load.bars == []
        assert len(load.rejections) == 1

    @pytest.mark.parametrize("column", ["price_open", "price_high",
                                        "price_low", "volume_traded"])
    def test_every_other_blank_numeric_column_is_fatal(self, tmp_path, column):
        load = self._load(tmp_path, self._row(**{column: ""}))
        assert load.bars == []
        assert len(load.rejections) == 1

    def test_a_populated_trades_count_is_still_read(self, tmp_path):
        load = self._load(tmp_path, self._row(trades_count="4242"))
        assert load.bars[0].trades == 4242

    def test_a_nonsense_trades_count_is_still_fatal(self, tmp_path):
        """"Empty" is a value. "banana" is corruption."""
        load = self._load(tmp_path, self._row(trades_count="banana"))
        assert load.bars == []

    def test_a_negative_trades_count_is_still_fatal(self, tmp_path):
        load = self._load(tmp_path, self._row(trades_count="-1"))
        assert load.bars == []

    def test_out_of_range_fields_are_rejected(self):
        for text in ("2024-13-01T00:00:00.0000000Z",
                     "2024-03-32T00:00:00.0000000Z",
                     "2024-03-01T25:00:00.0000000Z"):
            with pytest.raises(MarketDataError):
                md.parse_timestamp(text)

    def test_sub_microsecond_digits_truncate_rather_than_round(self):
        """Rounding up could move an event across a bar close, which is the one
        boundary the no-lookahead cut depends on."""
        assert (md.parse_timestamp("2024-03-01T00:00:00.0000009Z")
                == md.parse_timestamp("2024-03-01T00:00:00.0000000Z"))

    def test_a_non_string_is_rejected(self):
        with pytest.raises(MarketDataError):
            md.parse_timestamp(1_709_251_200)


