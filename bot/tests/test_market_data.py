class TestRejectionPaths:
    @pytest.mark.parametrize("relpath,kind,expected", anomaly_cases())
    def test_the_declared_rejection_fires(self, relpath, kind, expected):
        """Each fixture must produce exactly the reason the manifest declares."""
        load = LOADERS[kind](os.path.join(DATA, relpath))
        reasons = [rejection.reason for rejection in load.rejections]
        assert reasons == [expected], (
            f"{relpath}: expected exactly [{expected}], got {reasons}"
        )

    @pytest.mark.parametrize("relpath,kind,expected", anomaly_cases())
    def test_the_good_rows_survive_the_bad_one(self, relpath, kind, expected):
        """One bad row must not take the file down with it.

        Each fixture holds two genuinely valid rows plus one defect. A loader
        that aborts the whole file on the first problem is a different bug, and
        it is the one that makes people disable validation.
        """
        load = LOADERS[kind](os.path.join(DATA, relpath))
        assert len(rows_of(load)) >= 2

    @pytest.mark.parametrize("relpath,kind,expected", anomaly_cases())
    def test_the_rejection_carries_a_line_number_and_the_raw_row(
            self, relpath, kind, expected):
        load = LOADERS[kind](os.path.join(DATA, relpath))
        rejection = load.rejections[0]
        assert rejection.line >= 2, "line 1 is the header"
        assert rejection.raw, "the offending row must come back with the rejection"
        assert rejection.detail, "a reason code without a detail is not diagnosable"
        assert relpath.split("/")[-1] in str(rejection)

    @pytest.mark.parametrize("relpath,kind,expected", anomaly_cases())
    def test_strict_mode_raises_instead_of_collecting(self, relpath, kind, expected):
        with pytest.raises(MarketDataError) as excinfo:
            LOADERS[kind](os.path.join(DATA, relpath), strict=True)
        assert expected in str(excinfo.value)

    @pytest.mark.parametrize("relpath,kind,expected", anomaly_cases())
    def test_raise_if_rejected_refuses_the_load(self, relpath, kind, expected):
        load = LOADERS[kind](os.path.join(DATA, relpath))
        with pytest.raises(MarketDataError):
            load.raise_if_rejected()

    def test_every_declared_rejection_reason_is_in_the_vocabulary(self):
        for _relpath, _kind, expected in anomaly_cases():
            assert expected in RejectionReason.ALL

    def test_the_reason_vocabulary_is_complete(self):
        """`ALL` must list every constant, or a caller cannot enumerate them."""
        declared = {
            value for name, value in vars(RejectionReason).items()
            if name.isupper() and name != "ALL" and isinstance(value, str)
        }
        assert declared == set(RejectionReason.ALL)

    def test_a_wrong_header_is_fatal_not_five_thousand_rejections(self, tmp_path):
        """Every row would fail identically, which buries the one useful fact."""
        path = tmp_path / "wrong.csv"
        path.write_text("open,high,low,close\n1,2,0.5,1.5\n", encoding="utf-8")
        with pytest.raises(MarketDataError) as excinfo:
            md.load_ohlcv(str(path))
        assert "header" in str(excinfo.value).lower()

    def test_a_reordered_header_is_rejected(self, tmp_path):
        """These loaders read by position; a reordered file would parse cleanly
        into nonsense."""
        columns = list(md._OHLCV_COLUMNS)
        columns[4], columns[5] = columns[5], columns[4]
        path = tmp_path / "reordered.csv"
        path.write_text(",".join(columns) + "\n", encoding="utf-8")
        with pytest.raises(MarketDataError):
            md.load_ohlcv(str(path))

    def test_an_empty_file_is_rejected(self, tmp_path):
        path = tmp_path / "empty.csv"
        path.write_bytes(b"")
        with pytest.raises(MarketDataError):
            md.load_ohlcv(str(path))

    def test_rejection_reasons_are_counted_for_logging(self):
        load = md.load_ohlcv(os.path.join(DATA, "anomalies",
                                          "ohlcv_duplicate_timestamp.csv"))
        assert load.rejection_reasons == {RejectionReason.DUPLICATE_TIMESTAMP: 1}
        assert load.ok is False

    def test_a_clean_file_reports_ok(self, btc_bars):
        assert btc_bars.ok
        assert btc_bars.rejections == []

    def test_the_load_result_is_not_iterable(self, btc_bars):
        """Deliberate: `for bar in load_ohlcv(path)` must not work.

        If it did, a caller could consume the bars and never learn that rows
        were refused. Reaching for `.bars` is what puts `.rejections` in the
        same line of sight.
        """
        with pytest.raises(TypeError):
            iter(btc_bars)

    def test_duplicate_and_out_of_order_are_different_reasons(self):
        """A double-delivered message and an unsorted file need different fixes."""
        duplicate = md.load_ohlcv(
            os.path.join(DATA, "anomalies", "ohlcv_duplicate_timestamp.csv"))
        inverted = md.load_ohlcv(
            os.path.join(DATA, "anomalies", "ohlcv_out_of_order.csv"))
        assert duplicate.rejections[0].reason == RejectionReason.DUPLICATE_TIMESTAMP
        assert inverted.rejections[0].reason == RejectionReason.NON_MONOTONIC_TIMESTAMP

    def test_rows_are_not_sorted_before_checking(self):
        """Sorting first would repair the file and destroy the evidence."""
        load = md.load_ohlcv(
            os.path.join(DATA, "anomalies", "ohlcv_out_of_order.csv"))
        assert load.rejections, "an unordered source must be reported, not tidied"

    def test_an_interval_mismatch_is_its_own_reason(self):
        load = md.load_ohlcv(OHLCV_BTC, expected_interval_seconds=900)
        assert load.bars == []
        assert set(load.rejection_reasons) == {RejectionReason.INTERVAL_MISMATCH}

    def test_the_expected_interval_passes_on_the_real_file(self, manifest):
        load = md.load_ohlcv(OHLCV_BTC, expected_interval_seconds=3_600)
        assert load.ok and len(load.bars) == manifest["bars_per_symbol"]


