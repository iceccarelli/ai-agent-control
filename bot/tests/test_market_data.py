class TestOhlcvCorpus:
    @pytest.mark.parametrize("path", [OHLCV_BTC, OHLCV_ETH, OHLCV_SOL])
    def test_loads_without_a_single_rejection(self, path):
        load = md.load_ohlcv(path)
        assert load.ok, load.rejection_reasons
        assert len(load.bars) == load.rows_read

    def test_high_and_low_bracket_open_and_close(self, btc_bars):
        for bar in btc_bars.bars:
            assert bar.high >= max(bar.open, bar.close)
            assert bar.low <= min(bar.open, bar.close)

    def test_consecutive_bars_are_gap_consistent(self, btc_bars):
        """Each bar opens exactly where the previous one closed.

        The generator measures OHLC from a continuous tick path, so this is a
        real property of the data — and it is what makes the backtester's
        intrabar stop logic meaningful rather than an artefact of invented gaps.
        """
        bars = btc_bars.bars
        for previous, current in zip(bars, bars[1:]):
            assert current.open == pytest.approx(previous.close, rel=1e-12)

    def test_timestamps_are_strictly_increasing_and_evenly_spaced(self, btc_bars):
        bars = btc_bars.bars
        deltas = {b.open_us - a.open_us for a, b in zip(bars, bars[1:])}
        assert deltas == {3_600_000_000}

    def test_prices_are_positive_and_volume_is_not_negative(self, btc_bars):
        for bar in btc_bars.bars:
            assert min(bar.open, bar.high, bar.low, bar.close) > 0
            assert bar.volume >= 0 and bar.trades >= 0

    def test_bars_are_positionally_compatible_with_backtest_bar(self):
        """The compatibility claim in the module docstring, asserted.

        `market_data` must not import `backtest` (that would invert the
        dependency graph), so the compatibility is structural — and structural
        compatibility rots silently unless something checks it. The test may
        import both; the module may not.
        """
        import dataclasses

        import backtest

        theirs = [f.name for f in dataclasses.fields(backtest.Bar)]
        ours = [f.name for f in dataclasses.fields(md.Bar)]
        assert ours[:len(theirs)] == theirs, (
            "market_data.Bar no longer matches backtest.Bar positionally"
        )

    def test_a_loaded_bar_can_be_used_as_a_backtest_bar(self, btc_bars):
        import backtest

        bar = btc_bars.bars[0]
        assert bar.as_kline_row() == backtest.Bar(
            bar.start_ms, bar.open, bar.high, bar.low, bar.close, bar.volume
        ).as_kline_row()

    def test_close_series_feeds_the_indicators(self, btc_bars):
        """The point of the corpus: real-shaped input for the real math."""
        import pure_indicators as pi

        closes = btc_bars.closes()[:400]
        assert closes.shape == (400,)
        assert 0.0 <= float(pi.rsi(closes, 14)[-1]) <= 100.0

    def test_loading_is_deterministic(self):
        first = md.load_ohlcv(OHLCV_BTC).bars
        second = md.load_ohlcv(OHLCV_BTC).bars
        assert first == second

    def test_volume_is_autocorrelated_not_iid(self, btc_bars):
        """Clustered volume is the whole reason to model it.

        Anything that normalises by recent volume behaves differently against an
        i.i.d. series than against a real one, and would look better here than
        it will live.
        """
        volumes = np.array([bar.volume for bar in btc_bars.bars])
        centred = volumes - volumes.mean()
        lag1 = float((centred[:-1] * centred[1:]).sum() / (centred ** 2).sum())
        assert lag1 > 0.2, f"volume looks i.i.d. (lag-1 autocorrelation {lag1:.3f})"


